#!/usr/bin/env python3
"""Build splash.bin + splash.h from the 1-bit Ghosts Electronics logo."""

from pathlib import Path

from PIL import Image

MAX_WIDTH = 200
THRESHOLD = 128
SRC = Path(
    r"C:\Users\robertjo\.cursor\projects\c-Users-robertjo-Downloads-open-spec-analog-signed"
    r"\assets\c__Users_robertjo_AppData_Roaming_Cursor_User_workspaceStorage_"
    r"9825d2b1314f8a817e922ec57f6b2ef4_images_tshirt-logo-fb494a84-00ff-4688-8426-eef68f54a4b8.png"
)
OUT_DIR = Path(__file__).resolve().parent


def pack_bits(im: Image.Image) -> bytes:
    width, height = im.size
    row_bytes = (width + 7) // 8
    data = bytearray(height * row_bytes)
    pixels = im.load()
    for y in range(height):
        for x in range(width):
            if pixels[x, y] >= THRESHOLD:
                data[y * row_bytes + (x >> 3)] |= 0x80 >> (x & 7)
    return bytes(data)


def main() -> None:
    im = Image.open(SRC).convert("L")
    width, height = im.size
    if width > MAX_WIDTH:
        height = max(1, round(height * MAX_WIDTH / width))
        width = MAX_WIDTH
        im = im.resize((width, height), Image.Resampling.LANCZOS)

    packed = pack_bits(im)
    row_bytes = (width + 7) // 8
    (OUT_DIR / "splash.bin").write_bytes(packed)

    lines = [
        "/* Auto-generated by make_splash.py. 1-bit packed, MSB first, row-padded. */",
        "#ifndef SPLASH_H_",
        "#define SPLASH_H_",
        "",
        '#include "xil_types.h"',
        "",
        f"#define SPLASH_WIDTH     {width}U",
        f"#define SPLASH_HEIGHT    {height}U",
        f"#define SPLASH_ROW_BYTES {row_bytes}U",
        "",
        "static const u8 splash_bits[SPLASH_HEIGHT * SPLASH_ROW_BYTES] = {",
    ]
    for i in range(0, len(packed), 16):
        chunk = ", ".join(f"0x{b:02X}" for b in packed[i : i + 16])
        comma = "," if i + 16 < len(packed) else ""
        lines.append(f"\t{chunk}{comma}")
    lines.extend(["};", "", "#endif", ""])
    (OUT_DIR / "splash.h").write_text("\n".join(lines), encoding="ascii")

    ones = sum(bin(b).count("1") for b in packed)
    print(f"{width}x{height} packed {len(packed)} bytes, {ones} white pixels")
    print(f"wrote {OUT_DIR / 'splash.bin'}")
    print(f"wrote {OUT_DIR / 'splash.h'}")


if __name__ == "__main__":
    main()
